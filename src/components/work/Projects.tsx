import fs from "node:fs";
import path from "node:path";
import { getPosts } from "@/utils/utils";
import { WorkFolders, type WorkFolderGroup } from "@/components/work/WorkFolders";

type Project = ReturnType<typeof getPosts>[number];

/** `order` first (1, 2, 3...), then newest first. */
function byOrder(a: Project, b: Project) {
  const orderA = a.metadata.order ?? Number.POSITIVE_INFINITY;
  const orderB = b.metadata.order ?? Number.POSITIVE_INFINITY;
  if (orderA !== orderB) return orderA - orderB;
  return new Date(b.metadata.publishedAt).getTime() - new Date(a.metadata.publishedAt).getTime();
}

function hasPreview(slug: string) {
  return fs.existsSync(
    path.join(/*turbopackIgnore: true*/ process.cwd(), "public", "images", "previews", `${slug}.png`),
  );
}

function toFiles(projects: Project[]) {
  // The folder puts the LAST file at the front, so reverse: order 1 ends up in front.
  return [...projects].reverse().map((post) => ({
    name: post.metadata.company || post.metadata.title,
    meta: post.metadata.timeframe || undefined,
    // Generated by `npm run previews`; without one the file shows as a plain sheet.
    image: hasPreview(post.slug) ? `/images/previews/${post.slug}.png` : undefined,
    href: `/work/${post.slug}`,
  }));
}

/**
 * The Work folders: "Work Experience" and "Side Projects".
 * Each project's `category` frontmatter decides its folder.
 */
export function Projects() {
  const all = getPosts(["src", "app", "work", "projects"]).sort(byOrder);
  const experience = all.filter((p) => p.metadata.category === "experience");
  const projects = all.filter((p) => p.metadata.category !== "experience");

  const groups: WorkFolderGroup[] = [
    {
      label: "Work Experience",
      meta: `${experience.length} ${experience.length === 1 ? "role" : "roles"}`,
      art: "aurora",
      seed: 3,
      files: toFiles(experience),
    },
    {
      label: "Side Projects",
      meta: `${projects.length} ${projects.length === 1 ? "project" : "projects"}`,
      art: "dusk",
      seed: 7,
      files: toFiles(projects),
    },
  ].filter((g) => g.files.length > 0) as WorkFolderGroup[];

  return <WorkFolders groups={groups} />;
}
